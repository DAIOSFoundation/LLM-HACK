export const getTranslation = (key, language = 'ko') => {
  const keys = key.split('.');
  let value = translations[language];
  
  for (const k of keys) {
    if (value && typeof value === 'object' && k in value) {
      value = value[k];
    } else {
      return key; // 번역을 찾을 수 없으면 키를 반환
    }
  }
  
  return value || key;
};
